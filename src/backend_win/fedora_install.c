/*
 * fedora_install.c -- Unattended Fedora Workstation install.
 *
 * Ubuntu is installed on the host: its ISO carries a complete rootfs. Fedora's
 * Workstation ISO is a live image whose installer can't start by itself, so a VM
 * boots the netinstall ISO, whose Anaconda finds a Kickstart file on any volume
 * labelled OEMDRV. That file picks the packages (dnf, from Fedora's mirrors), lays
 * out btrfs the way Fedora does by default and copies this app's guest files in.
 * firstboot.sh then does what it does on Ubuntu.
 *
 * Unlike Ubuntu's, this needs internet during the install, from inside the VM.
 */
#include "fedora_install.h"

#include <stdio.h>

/* The pinned image. The hash is from Fedora's PGP-signed CHECKSUM file; a new
   release means updating all of these together. */
const wchar_t *const FEDORA_NETINST_URLS[] = {
    L"https://download.fedoraproject.org/pub/fedora/linux/releases/44/Everything/x86_64/iso/Fedora-Everything-netinst-x86_64-44-1.7.iso",
    L"https://mirrors.kernel.org/fedora/releases/44/Everything/x86_64/iso/Fedora-Everything-netinst-x86_64-44-1.7.iso",
};
const int FEDORA_NETINST_URL_COUNT = (int)(sizeof(FEDORA_NETINST_URLS) / sizeof(FEDORA_NETINST_URLS[0]));
const wchar_t FEDORA_NETINST_NAME[] = L"Fedora-Everything-netinst-x86_64-44-1.7.iso";
const wchar_t FEDORA_NETINST_SHA256[] = L"bd285201494dd0ba09b54d05ac707de1401668b8512a573edb5922dcf9d7067e";

/* Reports to the host's install watchdog over COM1, in the format firstboot.sh
   uses (asb_core.c, install_watch_line). Installs take far longer than the
   watchdog's silence limit, so the heartbeat runs for all of it, and it's also
   what notices an installer that has stopped moving: Anaconda stops at a prompt on
   errors kickstart can't express, and there's nobody there to answer. */
static const char FEDORA_KS_REPORT[] =
    "asb_report() {\n"
    "    printf '\\nASB-FIRSTBOOT:%s\\n' \"$(printf '%s' \"$*\" | LC_ALL=C tr -cd '[:print:]' | head -c 400)\" > /dev/ttyS0 2>/dev/null\n"
    "}\n"
    "asb_report_failure() {\n"
    "    for _i in 1 2 3; do asb_report \"FAIL $1\"; sleep 2; done\n"
    "}\n"
    /* What dnf or Anaconda said, for the host's error message. */
    "asb_installer_error() {\n"
    /* The usual cause, and otherwise buried in a line of Python repr. */
    "    _e=$(cat /tmp/packaging.log /tmp/dnf.log /tmp/anaconda.log 2>/dev/null | "
    "grep -o -m1 \"No match for argument: [^'\\\"]*\")\n"
    "    [ -n \"$_e\" ] || _e=$(cat /tmp/packaging.log /tmp/dnf.log /tmp/anaconda.log /tmp/storage.log 2>/dev/null | "
    "grep -m1 -E 'CRITICAL|ERROR|Error: |Failed to|failed to|Problem:' | "
    "sed 's/^[^ ]* *[A-Z]* *[^ ]* *//')\n"
    "    printf '%s' \"$_e\" | head -c 240\n"
    "}\n";

BOOL fedora_kickstart_write(const wchar_t *path, const FedoraKickstart *ks)
{
    FILE *f = NULL;
    if (_wfopen_s(&f, path, L"wb") != 0 || !f) return FALSE;

    fprintf(f, "# Generated by App Sandbox. See src/backend_win/fedora_install.c.\n");
    fprintf(f, "text\n");
    fprintf(f, "lang %s\n", ks->locale);
    fprintf(f, "keyboard --xlayouts=%s\n", ks->keyboard);
    fprintf(f, "timezone %s --utc\n", ks->tz);

    if (ks->static_ip[0]) {
        fprintf(f, "network --bootproto=static --device=%s --ip=%s --netmask=255.255.255.0"
                   " --gateway=%s --nameserver=%s,8.8.8.8 --activate --onboot=yes --hostname=%s\n",
                ks->mac[0] ? ks->mac : "link", ks->static_ip, ks->gateway, ks->gateway, ks->hostname);
    } else {
        fprintf(f, "network --bootproto=dhcp --device=link --activate --onboot=yes --hostname=%s\n",
                ks->hostname);
    }

    /* Mirrors, not the ISO: the netinstall ISO has an installer but no packages. */
    fprintf(f, "url --mirrorlist=https://mirrors.fedoraproject.org/mirrorlist?repo=fedora-%s&arch=x86_64\n",
            ks->release);
    fprintf(f, "repo --name=asb-updates --mirrorlist=https://mirrors.fedoraproject.org/mirrorlist?repo=updates-released-f%s&arch=x86_64\n",
            ks->release);

    /* firstboot.sh creates the user from the same markers as on Ubuntu. */
    fprintf(f, "rootpw --lock\n");
    fprintf(f, "selinux --enforcing\n");
    fprintf(f, "firewall --enabled --service=ssh\n");
    fprintf(f, "firstboot --disable\n");

    /* Fedora's default layout: ESP, /boot, then btrfs with root and home subvolumes.
       btrfs comes last, which is what lets a grown disk reach it. */
    fprintf(f, "ignoredisk --only-use=sda\n");
    fprintf(f, "zerombr\n");
    fprintf(f, "clearpart --all --initlabel --drives=sda\n");
    fprintf(f, "autopart --type=btrfs --noswap\n");
    /* console= for the host's COM1 log; video= so only asb_drm drives a display,
       matching the grub drop-in firstboot.sh writes on Ubuntu. */
    fprintf(f, "bootloader --append=\"console=tty0 console=ttyS0,115200 video=efifb:off video=simplefb:off\"\n");
    fprintf(f, "reboot\n\n");

    /* kernel-devel-matched keeps headers in step with every future kernel update
       so DKMS can rebuild; kernel-modules-extra holds snd-aloop, which audio needs. */
    fprintf(f, "%%packages\n"
               "@^workstation-product-environment\n"
               "gcc\nmake\ndkms\nkernel-devel-matched\nkernel-modules-extra\n"
               "alsa-lib-devel\nlibxcb-devel\nlibdrm-devel\npkgconf-pkg-config\n"
               "cifs-utils\nzstd\ncloud-utils-growpart\nbtrfs-progs\nopenssh-server\n"
               "flatpak\nmesa-dri-drivers\nmesa-vulkan-drivers\n"
               "-gnome-initial-setup\n-gnome-tour\n"
               "%%end\n\n");

    /* --erroronfail would stop at a prompt; report it instead (see above). */
    fprintf(f, "%%pre --log=/tmp/asb-pre.log\n%s", FEDORA_KS_REPORT);
    fprintf(f,
        "asb_report START\n"
        "asb_report \"STEP Installing Fedora\"\n"
        "(\n"
        "    last=\"\"; still=0\n"
        "    while sleep 30; do\n"
        "        [ -e /tmp/asb-install-over ] && exit 0\n"
        "        asb_report HEARTBEAT\n"
        /* Every stage of the install writes to one of these. */
        "        now=$(cat /tmp/packaging.log /tmp/dnf.log /tmp/anaconda.log /tmp/program.log /tmp/storage.log 2>/dev/null | wc -c)\n"
        "        if [ \"$now\" = \"$last\" ]; then still=$((still + 30)); else still=0; last=$now; fi\n"
        "        if [ \"$still\" -ge 1200 ]; then\n"
        "            asb_report_failure \"The Fedora installer stopped for 20 minutes: $(asb_installer_error)\"\n"
        "            exit 0\n"
        "        fi\n"
        "    done\n"
        ") </dev/null >/dev/null 2>&1 &\n"
        "%%end\n\n");

    /* Anaconda calls this on fatal errors, then waits for a reboot nobody will ask for. */
    fprintf(f, "%%onerror\n%s", FEDORA_KS_REPORT);
    fprintf(f,
        "touch /tmp/asb-install-over\n"
        "asb_report_failure \"The Fedora installer failed: $(asb_installer_error)\"\n"
        "%%end\n\n");

    /* --nochroot: the media isn't visible from the installed system. Same effect
       as stage_manifest_into_rootfs on the Ubuntu path. */
    fprintf(f, "%%post --nochroot --log=/mnt/sysroot/root/asb-post-nochroot.log\n%s", FEDORA_KS_REPORT);
    fprintf(f,
        "asb_report \"STEP Copying App Sandbox files\"\n"
        "mkdir -p /mnt/asbmedia\n"
        "if ! mount -o ro /dev/disk/by-label/OEMDRV /mnt/asbmedia; then\n"
        "    asb_report_failure \"The installer couldn't read the App Sandbox install disc\"\n"
        "    exit 1\n"
        "fi\n"
        "cp -r /mnt/asbmedia/rootfs/. /mnt/sysroot/\n"
        "install -D -m 0755 /mnt/asbmedia/appsandbox-firstboot.sh /mnt/sysroot/usr/local/bin/appsandbox-firstboot.sh\n"
        "install -D -m 0644 /mnt/asbmedia/appsandbox-firstboot.service /mnt/sysroot/etc/systemd/system/appsandbox-firstboot.service\n"
        /* The media is read-only, and cp keeps that. */
        "chmod -R u+w,go-w /mnt/sysroot/opt/appsandbox\n"
        "chmod 0600 /mnt/sysroot/etc/appsandbox-admin-hash 2>/dev/null\n"
        "umount /mnt/asbmedia\n"
        /* Not in the next section: its /tmp is the installed system's. */
        "touch /tmp/asb-install-over\n"
        "%%end\n\n");

    fprintf(f, "%%post --log=/root/asb-post.log\n");
    fprintf(f,
        "restorecon -RF /opt/appsandbox /usr/local/bin /etc/systemd/system /etc/appsandbox-* 2>/dev/null\n"
        "systemctl enable appsandbox-firstboot.service\n"
        "%%end\n");

    fclose(f);
    return TRUE;
}
